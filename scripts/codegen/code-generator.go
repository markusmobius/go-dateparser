package main

import (
	"bytes"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func generateCode(tplName string, data any, dstPath string) error {
	// Generate code
	b := bytes.NewBuffer(nil)
	err := templates[tplName].Execute(b, data)
	if err != nil {
		return err
	}

	// Format code
	code, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	// Save to file
	return os.WriteFile(dstPath, code, os.ModePerm)
}

// removeGeneratedCode deletes the Go files in dir except tests, which aren't generated.
func removeGeneratedCode(dir string) error {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}

func generateLocaleDataCode(dstPath string, listData []LocaleData) error {
	// Generate code
	b := bytes.NewBuffer(nil)
	b.WriteString(`
	// Code is generated by script; DO NOT EDIT.

	package data
	import (
		"sync"

		"github.com/markusmobius/go-dateparser/internal/regexp"
	)
	`)

	// Generate locale data
	err := templates["locale-data"].Execute(b, listData)
	if err != nil {
		return err
	}

	// Remove empty fields
	code := b.Bytes()
	code = rxGoEmptyField.ReplaceAll(code, []byte(""))
	code = rxGoZeroField.ReplaceAll(code, []byte(""))

	nRegex := bytes.Count(code, []byte("regexp"))
	if nRegex <= 1 {
		code = rxGoRegexImport.ReplaceAll(code, []byte(""))
	}

	// Format code
	code, err = format.Source(code)
	if err != nil {
		return err
	}

	// Save to file
	return os.WriteFile(dstPath, code, os.ModePerm)
}
